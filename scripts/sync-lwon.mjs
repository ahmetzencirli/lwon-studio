// Copies the LWON library, spec and benchmark data from a sibling checkout of
// github.com/ahmetzencirli/lwon. Until the `lwon` package is on npm the site
// vendors these files; run `npm run sync` after changing them in that repo.
import { cpSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';

const root = new URL('../../lwon/', import.meta.url);
const here = new URL('../src/', import.meta.url);
const banner = (from) => `// Generated by scripts/sync-lwon.mjs from lwon/${from}. Do not edit here.\n`;

const lib = new URL('lib/lwon/', here);
rmSync(lib, { recursive: true, force: true });
mkdirSync(lib, { recursive: true });
for (const f of readdirSync(new URL('packages/lwon/src/', root))) {
  if (!f.endsWith('.ts') || f === 'cli.ts') continue;
  const src = readFileSync(new URL(`packages/lwon/src/${f}`, root), 'utf8');
  writeFileSync(new URL(f, lib), banner(`packages/lwon/src/${f}`) + src);
}

cpSync(new URL('SPEC.md', root), new URL('content/spec.md', here));
cpSync(new URL('bench/results.json', root), new URL('data/bench.json', here));
cpSync(new URL('bench/eval/results.json', root), new URL('data/eval.json', here));
cpSync(new URL('bench/eval/results-sparse.json', root), new URL('data/eval-sparse.json', here));
cpSync(new URL('bench/data/', root), new URL('data/samples/', here), { recursive: true });
console.log('Synced lwon library, spec and benchmark data.');
